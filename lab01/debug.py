# Обязательное задание 3. Поиск и исправление ошибок.
# Три независимых фрагмента. Для А и Б печатаем типы значений до и после
# преобразования, в комментариях объясняем каждую ошибку.

print("Фрагмент А: сумма чисел 2 и 3")

# Ошибка была в том, что first и second — строки ("2" и "3"), поэтому
# операция + соединяла их в строку "23", а не складывала числа.
# Ожидаемый результат после исправления — 5.
first_text = "2"
second_text = "3"
print("Тип до преобразования:", type(first_text), type(second_text))

first = int(first_text)
second = int(second_text)
print("Тип после преобразования:", type(first), type(second))

sum_a = first + second
print("Результат А (сумма):", sum_a)

print()
print("Фрагмент Б: возраст через год")

# Ошибка была в том, что input() возвращает строку, и age + 1 пыталось
# сложить строку с числом — это ошибка TypeError. Нужно преобразовать
# ввод в int. Проверочный ввод — 17, ожидаемый результат — 18.
age_text = input("Возраст: ")
print("Тип до преобразования:", type(age_text))

age = int(age_text)
print("Тип после преобразования:", type(age))

age_next_year = age + 1
print("Результат Б (возраст через год):", age_next_year)

print()
print("Фрагмент В: среднее трёх чисел")

# Ошибка была в порядке вычислений: из-за приоритета операций сначала
# выполнялось third / 3, и только потом сложение, то есть 4 + 7 + 10/3.
# Нужно сложить числа в скобках и разделить сумму на 3.
# Ожидаемый результат — 7.0.
first = 4
second = 7
third = 10
average = (first + second + third) / 3
print("Результат В (среднее):", average)
