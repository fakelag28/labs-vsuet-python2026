# Лабораторная работа 4. Задание 3. Повторный ввод
# Запрашиваем целое число, пока не введено положительное.
# Затем выводим его квадрат и количество отклонённых попыток.

rejected = 0
number = int(input("Введите положительное целое число: "))

while number <= 0:
    rejected += 1
    number = int(input("Число должно быть положительным, попробуйте снова: "))

print(f"Квадрат: {number * number}")
print(f"Отклонено попыток: {rejected}")
