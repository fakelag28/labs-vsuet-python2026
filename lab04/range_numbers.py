# Лабораторная работа 4. Задание 1. Диапазон в обе стороны
# Ввод целых a и b -> вывод всех чисел от a до b включительно.
# По возрастанию при a < b, по убыванию при a > b, одно число при равенстве.

a = int(input("Первое число a: "))
b = int(input("Второе число b: "))

if a <= b:
    step = 1
else:
    step = -1

for number in range(a, b + step, step):
    print(number)
