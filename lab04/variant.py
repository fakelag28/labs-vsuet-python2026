# Лабораторная работа 4. Индивидуальный вариант 1. "Чётные числа"
# Ввод n >= 0, затем n целых чисел.
# Одним циклом: количество и сумма чётных значений.
# Ноль кратен любому ненулевому целому, значит ноль чётный.
# Список не используется, подсчёт ведётся в цикле.

n = int(input("Сколько чисел будет введено (n >= 0): "))

count = 0
total = 0

for index in range(n):
    number = int(input(f"Число {index + 1}: "))
    if number % 2 == 0:
        count += 1
        total += number

print(f"Количество чётных: {count}")
print(f"Сумма чётных: {total}")
