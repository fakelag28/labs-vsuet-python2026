"""Работа с прямоугольной таблицей целых чисел.

Модуль скопирован и адаптирован из лабораторной работы №9 «Вложенные списки
и таблицы». Здесь оставлены только функции суммирования, нужные работе №10:
row_sums и column_sums. Функции не изменяют полученную матрицу.
"""


def row_sums(matrix):
    """Возвращает список сумм строк таблицы.

    Для пустой таблицы возвращает пустой список.
    """
    return [sum(row) for row in matrix]


def column_sums(matrix):
    """Возвращает список сумм столбцов таблицы.

    Для пустой таблицы возвращает пустой список. Непустая матрица
    прямоугольная и имеет хотя бы один столбец.
    """
    if not matrix:
        return []
    columns = len(matrix[0])
    return [sum(row[column] for row in matrix) for column in range(columns)]
